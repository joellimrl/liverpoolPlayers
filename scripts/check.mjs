import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {load} from 'cheerio';
import {Script} from 'node:vm';
import {validateArchive} from './parser.mjs';
const root=new URL('../',import.meta.url);
const html=await readFile(new URL('index.html',root),'utf8');
const data=JSON.parse(await readFile(new URL('data/archive.json',root),'utf8'));
validateArchive(data);
const $=load(html);
if($('script[src],link[rel=stylesheet],iframe,img').length)throw new Error('Site must be self-contained');
if($('script#archive-data').length!==1)throw new Error('Missing embedded data');
if(JSON.stringify(JSON.parse($('#archive-data').text()))!==JSON.stringify(data))throw new Error('HTML embeds stale data');
if($('#squad-body>tr').length!==data.squad.length || $('#transfers-body>tr').length!==data.transfers.length)throw new Error('Static tables are incomplete');
for(const script of $('script').toArray())if($(script).attr('type')!=='application/json')new Script($(script).text());
const ids=$('[id]').map((_,el)=>$(el).attr('id')).get();
if(new Set(ids).size!==ids.length)throw new Error('Duplicate HTML IDs');
if(Buffer.byteLength(html)>5*1024*1024)throw new Error('HTML exceeded 5 MB size budget');
console.log(`Verified ${fileURLToPath(new URL('index.html',root))}: embedded snapshot, static rows, JS syntax, IDs, no runtime dependencies.`);
